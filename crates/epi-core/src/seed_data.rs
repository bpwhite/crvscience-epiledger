pub fn builtin_measles_weekly_dataset() -> TimeSeriesDataset {
    let points: Vec<TimeSeriesPoint> = CDC_MEASLES_WEEKLY_2022_2026
        .iter()
        .map(|(dt, c)| TimeSeriesPoint {
            date_label: (*dt).to_string(),
            epiweek: parse_flexible_date_to_mmwr(dt),
            count: f64::from(*c),
            suppressed: false,
        })
        .collect();

    TimeSeriesDataset {
        vintage_id: "cdc_measles_2022_2026_v1".to_string(),
        title: "CDC US Confirmed Measles Cases by Rash Onset (2022-2026)".to_string(),
        source_kind: SourceKind::VerifiedSnapshot,
        source_url: "https://www.cdc.gov/measles/data-research/index.html".to_string(),
        ingested_at_utc: "2026-11-06T12:00:00Z".to_string(),
        default_si_preset: "measles".to_string(),
        checksum_hex: "b84f31e2".to_string(),
        points,
    }
}

